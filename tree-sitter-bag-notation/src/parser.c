static bool ts_lex(TSLexer *lexer, TSStateId state) {
  START_LEXER();
  eof = lexer->eof(lexer);
  switch (state) {
    case 0:
      if (eof) ADVANCE(9);
      if (lookahead == '\n') ADVANCE(10);
      if (lookahead == '#') ADVANCE(26);
      if (lookahead == '(') ADVANCE(12);
      if (lookahead == ')') ADVANCE(13);
      if (lookahead == '-') ADVANCE(24);
      if (lookahead == ':') ADVANCE(15);
      if (lookahead == '\t' ||
          lookahead == ' ') ADVANCE(25);
      if (lookahead == '_' ||
          lookahead == '~') ADVANCE(23);
      if (lookahead == '+' ||
          lookahead == '.' ||
          lookahead == '/') ADVANCE(22);
      if (('a' <= lookahead && lookahead <= 'h') ||
          lookahead == 'l') ADVANCE(21);
      if (lookahead == '&' ||
          lookahead == '\'' ||
          (',' <= lookahead && lookahead <= '4') ||
          lookahead == '=' ||
          lookahead == '^') ADVANCE(14);
      if (('j' <= lookahead && lookahead <= 'v') ||
          ('x' <= lookahead && lookahead <= 'z')) ADVANCE(20);
      END_STATE();
    case 1:
      if (lookahead == '\n') ADVANCE(10);
      if (lookahead == '#') ADVANCE(26);
      if (lookahead == '(') ADVANCE(12);
      if (lookahead == ':') ADVANCE(6);
      if (lookahead == '\t' ||
          lookahead == ' ') ADVANCE(25);
      if (lookahead == 'i' ||
          lookahead == '|') ADVANCE(19);
      if (lookahead == '+' ||
          lookahead == '.' ||
          lookahead == '/') ADVANCE(22);
      if (lookahead == '-' ||
          lookahead == '_' ||
          lookahead == '~') ADVANCE(23);
      if (('a' <= lookahead && lookahead <= 'h') ||
          lookahead == 'l') ADVANCE(21);
      if (lookahead == '&' ||
          lookahead == '\'' ||
          (',' <= lookahead && lookahead <= '4') ||
          lookahead == '=' ||
          lookahead == '^') ADVANCE(14);
      if (('j' <= lookahead && lookahead <= 'v') ||
          ('x' <= lookahead && lookahead <= 'z')) ADVANCE(20);
      END_STATE();
    case 2:
      if (lookahead == '\n') ADVANCE(11);
      END_STATE();
    case 3:
      if (lookahead == '-') ADVANCE(4);
      END_STATE();
    case 4:
      if (lookahead == '-') ADVANCE(2);
      END_STATE();
    case 5:
      if (lookahead == '-') ADVANCE(3);
      if (lookahead == ' ' ||
          lookahead == '\'' ||
          ('A' <= lookahead && lookahead <= 'Z') ||
          ('a' <= lookahead && lookahead <= 'z')) ADVANCE(16);
      END_STATE();
    case 6:
      if (lookahead == 'i' ||
          lookahead == '|') ADVANCE(19);
      END_STATE();
    case 7:
      if (lookahead != 0 &&
          lookahead != '\n' &&
          lookahead != ')') ADVANCE(17);
      END_STATE();
    case 8:
      if (eof) ADVANCE(9);
      if (lookahead == '\n') ADVANCE(10);
      if (lookahead == '#') ADVANCE(26);
      if (lookahead == '(') ADVANCE(12);
      if (lookahead == '-') ADVANCE(3);
      if (lookahead == ':') ADVANCE(6);
      if (lookahead == '\t' ||
          lookahead == ' ') ADVANCE(25);
      if (lookahead == 'i' ||
          lookahead == '|') ADVANCE(19);
      if (('a' <= lookahead && lookahead <= 'h') ||
          lookahead == 'l') ADVANCE(21);
      if (lookahead == '&' ||
          lookahead == '\'' ||
          lookahead == ',' ||
          ('0' <= lookahead && lookahead <= '4') ||
          lookahead == '=' ||
          lookahead == '^') ADVANCE(14);
      if (('j' <= lookahead && lookahead <= 'v') ||
          ('x' <= lookahead && lookahead <= 'z')) ADVANCE(20);
      END_STATE();
    case 9:
      ACCEPT_TOKEN(ts_builtin_sym_end);
      END_STATE();
    case 10:
      ACCEPT_TOKEN(anon_sym_LF);
      END_STATE();
    case 11:
      ACCEPT_TOKEN(anon_sym_DASH_DASH_DASH_LF);
      END_STATE();
    case 12:
      ACCEPT_TOKEN(anon_sym_LPAREN);
      END_STATE();
    case 13:
      ACCEPT_TOKEN(anon_sym_RPAREN);
      END_STATE();
    case 14:
      ACCEPT_TOKEN(sym_shorthand_label);
      END_STATE();
    case 15:
      ACCEPT_TOKEN(anon_sym_COLON);
      END_STATE();
    case 16:
      ACCEPT_TOKEN(sym_field_label);
      if (lookahead == ' ' ||
          lookahead == '\'' ||
          ('A' <= lookahead && lookahead <= 'Z') ||
          ('a' <= lookahead && lookahead <= 'z')) ADVANCE(16);
      END_STATE();
    case 17:
      ACCEPT_TOKEN(sym_field_value);
      if (lookahead != 0 &&
          lookahead != '\n' &&
          lookahead != ')') ADVANCE(17);
      END_STATE();
    case 18:
      ACCEPT_TOKEN(sym_barline);
      END_STATE();
    case 19:
      ACCEPT_TOKEN(sym_barline);
      if (lookahead == ':') ADVANCE(18);
      if (lookahead == 'i' ||
          lookahead == '|') ADVANCE(19);
      END_STATE();
    case 20:
      ACCEPT_TOKEN(sym_embellishment);
      if (lookahead == 'j' ||
          lookahead == 'k' ||
          ('m' <= lookahead && lookahead <= 'v') ||
          ('x' <= lookahead && lookahead <= 'z')) ADVANCE(20);
      END_STATE();
    case 21:
      ACCEPT_TOKEN(sym_pitch);
      END_STATE();
    case 22:
      ACCEPT_TOKEN(sym_duration);
      if (lookahead == '+' ||
          lookahead == '.' ||
          lookahead == '/') ADVANCE(22);
      END_STATE();
    case 23:
      ACCEPT_TOKEN(sym_connector);
      END_STATE();
    case 24:
      ACCEPT_TOKEN(sym_connector);
      if (lookahead == '-') ADVANCE(4);
      END_STATE();
    case 25:
      ACCEPT_TOKEN(sym__whitespace);
      if (lookahead == '\t' ||
          lookahead == ' ') ADVANCE(25);
      END_STATE();
    case 26:
      ACCEPT_TOKEN(anon_sym_POUND);
      END_STATE();
    case 27:
      ACCEPT_TOKEN(aux_sym_comment_token1);
      if (lookahead != 0 &&
          lookahead != '\n') ADVANCE(27);
      END_STATE();
    default:
      return false;
  }
}

